"""Web host surface: an HTML tool host for pyRevit (WebView2 inside a WPF window).

Generates, inside the firm extension, an IronPython 2.7 package (``lib/<namespace>_web``)
that hosts a tool's HTML in a WebView2 control, the generated assets that HTML loads
(bridge script, helper script, token-built stylesheet, packaged fonts, firm symbol), and a
read-only ``Web Tool Demo`` pushbutton: a report console that lists view counts by view type.

The WebView2 assemblies are not shipped. Every Revit from 2024 carries
``Microsoft.Web.WebView2.Core`` and ``.Wpf`` beside ``Revit.exe``; the generated host finds
them at run time in the running Revit folder and creates the WebView2 environment itself,
which avoids a defect in the Wpf assembly that Revit 2024 bundles. See FOUNDATION_SPEC 8.5.

Ported from Rob Mintzes's Rockwell Group pyRevit web library under the scoped permission
recorded in ADR 0005; see docs/product/RELEASE_RECORD.md (R06). Nothing here is live-verified
in Revit.
"""

from __future__ import annotations

