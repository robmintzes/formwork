from toolkit_engine.profile import Profile
from toolkit_engine.textutil import html, kebab, md, py_string, render_file, xml, yaml_scalar
from toolkit_engine.tokens import Color

ADAPTER_ID = "web-host"
TOOLTIP = "Shows view counts by view type in an HTML report console hosted in WebView2. Read-only."

